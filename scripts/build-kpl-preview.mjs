import fs from 'node:fs';
const s = fs.readFileSync(new URL('../src/data/kpl.full.generated.ts', import.meta.url), 'utf8');
const read = (marker, end) => JSON.parse(s.slice(s.indexOf(marker) + marker.length, s.indexOf(end, s.indexOf(marker)) + 1));
const poets = read('const poets: Poet[] = ', '];');
const edges = read('const edges: PoemEdge[] = ', '];');
const limits = { Season: 23, Club: 37, Player: 100, Hero: 60, Match: 48 };
const ids = new Set();
for (const [type, limit] of Object.entries(limits)) poets.filter((node) => node.type === type).slice(0, limit).forEach((node) => ids.add(node.id));
const previewEdges = edges.filter((edge) => ids.has(edge.source) && ids.has(edge.target)).slice(0, 16770);
const output = `import type { DynastyDataset, Poet, PoemEdge } from './types';\n\nconst poets: Poet[] = ${JSON.stringify(poets.filter((node) => ids.has(node.id)))};\nconst edges: PoemEdge[] = ${JSON.stringify(previewEdges)};\nexport const kplData: DynastyDataset = { poets, edges };\n`;
fs.writeFileSync(new URL('../src/data/kpl.generated.ts', import.meta.url), output);
console.log(`Generated preview: ${ids.size} nodes, ${previewEdges.length} edges`);
